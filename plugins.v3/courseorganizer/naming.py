def _candidate_names(candidate: MetadataCandidate) -> Tuple[str, ...]:
    names = [candidate.title, candidate.en_title, candidate.original_title]
    names.extend(candidate.aliases)
    return tuple(name for name in names if name)


def _aliases_signature(candidate: MetadataCandidate) -> set[str]:
    signatures: set[str] = set()
    for name in _candidate_names(candidate):
        normalized = normalize_title(name)
        if normalized:
            signatures.add(normalized)
    return signatures


def _cross_source_corroboration(items: Sequence[ScoredCandidate]) -> bool:
    if len(items) < 2:
        return False
    sources = {item.candidate.source for item in items}
    if not {"themoviedb", "douban"} <= sources:
        return False
    years = {item.candidate.year for item in items}
    if len(years) != 1 or None in years:
        return False
    base = _aliases_signature(items[0].candidate)
    for item in items[1:]:
        if not (base & _aliases_signature(item.candidate)):
            return False
    return True


def _hard_reject(hints: TitleHints, candidate: MetadataCandidate, directory: DirectoryHints) -> Optional[str]:
    if not _candidate_names(candidate):
        return "empty_title"
    if hints.year is not None and candidate.year is not None and hints.year != candidate.year:
        return "year_mismatch"
    if directory.episodic and candidate.media_type == "movie":
        return "episodic_movie"
    if not candidate.media_id:
        return "missing_source_id"
    return None


def _query_score(query: QueryCandidate, candidate: MetadataCandidate) -> Tuple[int, Optional[str]]:
    query_normalized = normalize_title(query.text)
    if not query_normalized:
        return 0, "no_query"
    exact_map = {
        "exact_title": candidate.title,
        "exact_original_title": candidate.original_title,
        "exact_en_title": candidate.en_title,
    }
    for key, title in exact_map.items():
        if normalize_title(title) == query_normalized:
            return 80, key

    for alias in _candidate_names(candidate):
        if normalize_title(alias) == query_normalized and alias not in (
            candidate.title,
            candidate.en_title,
            candidate.original_title,
        ):
            return 76, "exact_alias"

    query_tokens = set(tokenize_title(query.text))
    alias_tokens = {token for alias in _candidate_names(candidate) for token in tokenize_title(alias)}
    if query_tokens and query_tokens == alias_tokens:
        return 72, "token_set_exact"

    score = 0.0
    for alias in _candidate_names(candidate):
        alias_normalized = normalize_title(alias)
        if not alias_normalized:
            continue
        score = max(score, SequenceMatcher(None, query_normalized, alias_normalized).ratio())
        score = max(score, token_similarity(query.text, alias))
    if score <= 0.0:
        return 0, "no_match"
    return round(65 * score), None


def score_candidates(
    hints: TitleHints, directory: DirectoryHints, candidates: Sequence[MetadataCandidate]
) -> Tuple[ScoredCandidate, ...]:
    scored: List[ScoredCandidate] = []
    for candidate in candidates:
        rejected = _hard_reject(hints, candidate, directory)
        best = 0
        reasons: List[str] = []
        for query in hints.query_candidates:
            base, reason = _query_score(query, candidate)
            if reason:
                reasons.append(reason)
            score = base + query.quality_bonus
            if score > best:
                best = score

        if hints.year is not None and candidate.year == hints.year:
            reasons.append("year_match")
            best += 10
        if directory.episodic and candidate.media_type == "tv":
            reasons.append("episodic_tv")
            best += 8
        best = max(0, min(100, best))

        scored.append(
            ScoredCandidate(
                candidate=candidate,
                score=best,
                reason_codes=_ordered_reasons(reasons),
                rejected_reason=rejected or "",
            )
        )
    return tuple(scored)


def _cluster_candidates(candidates: Sequence[ScoredCandidate]) -> List[List[int]]:
    if not candidates:
        return []
    parent = list(range(len(candidates)))

    def find(index: int) -> int:
        while parent[index] != index:
            parent[index] = parent[parent[index]]
            index = parent[index]
        return index

    def union(left: int, right: int) -> None:
        left_root = find(left)
        right_root = find(right)
        if left_root != right_root:
            parent[right_root] = left_root

    for left_index, left_item in enumerate(candidates):
        left = left_item.candidate
        left_sig = _aliases_signature(left)
        for right_index in range(left_index + 1, len(candidates)):
            right = candidates[right_index].candidate
            if left.media_type != right.media_type:
                continue
            if left.year != right.year or left.year is None:
                continue
            if not (left_sig & _aliases_signature(right)):
                continue
            union(left_index, right_index)

    groups: Dict[int, List[int]] = {}
    for index in range(len(candidates)):
        groups.setdefault(find(index), []).append(index)
    return list(groups.values())


def evaluate_candidates(
    hints: TitleHints,
    directory: DirectoryHints,
    candidates: Sequence[MetadataCandidate],
    auto_threshold: int = 90,
    min_margin: int = 12,
) -> MatchEvaluation:
    scored = score_candidates(hints, directory, candidates)
    if not scored:
        return MatchEvaluation("local_fallback", None, (), 0, ("no_candidates",))

    eligible = tuple(item for item in scored if not item.rejected_reason)
    if not eligible:
        return MatchEvaluation("local_fallback", None, (), 0, ("all_rejected",))

    grouped_indexes = _cluster_candidates(eligible)
    grouped: List[Tuple[ScoredCandidate, List[ScoredCandidate]]] = []
    for group in grouped_indexes:
        members = [eligible[index] for index in group]
        members.sort(
            key=lambda item: (item.score, -item.candidate.source_rank),
            reverse=True,
        )
        top = members[0]
        cluster_reason = list(top.reason_codes)
        bonus = _cross_source_corroboration(members)
        if bonus:
            cluster_reason.append("cross_source_corroboration")
        grouped.append(
            (
                ScoredCandidate(
                    candidate=top.candidate,
                    score=min(100, top.score + (5 if bonus else 0)),
                    reason_codes=_ordered_reasons(cluster_reason),
                    rejected_reason=top.rejected_reason,
                ),
                members,
            )
        )

    grouped.sort(
        key=lambda item: (
            item[0].score,
            -item[0].candidate.source_rank,
        ),
        reverse=True,
    )
    ordered = tuple(item[0] for item in grouped)

    if not ordered:
        return MatchEvaluation("local_fallback", None, (), 0, ("all_rejected",))

    top = ordered[0]
    second_score = ordered[1].score if len(ordered) > 1 else 0
    margin = int(top.score - second_score)

    if top.score < 70:
        return MatchEvaluation("local_fallback", top, ordered, margin, ("score_too_low",))

    short_title = len(normalize_title(hints.local_title)) < 4
    if short_title:
        top_group = grouped[0][1]
        year_ok = hints.year is not None and top.candidate.year is not None and hints.year == top.candidate.year
        cross = _cross_source_corroboration(top_group)
        if not (year_ok or cross):
            return MatchEvaluation("review", top, ordered, margin, ("short_title_risk",))

    if top.score >= auto_threshold and margin >= min_margin:
        return MatchEvaluation("auto_external", top, ordered, margin, ("auto_threshold_met",))

    if top.score >= 70 and (top.score >= auto_threshold or margin >= min_margin):
        return MatchEvaluation("review", top, ordered, margin, ("review_needed",))

    return MatchEvaluation("review", top, ordered, margin, ("needs_manual_review",))


def _select_title_by_query(hints: TitleHints, candidate: MetadataCandidate) -> str:
    en_title = normalize_title(candidate.en_title)
    original_title = normalize_title(candidate.original_title)
    for query in hints.query_candidates:
        normalized = normalize_title(query.text)
        if normalized and normalized in {en_title, original_title}:
            return candidate.en_title or candidate.original_title
    return candidate.title or candidate.en_title or candidate.original_title


def format_root_name(hints: TitleHints, candidate: Optional[MetadataCandidate], append_tmdb_id: bool = False) -> str:
    if candidate is None:
        root = hints.local_title
        if hints.year is not None:
            root += f" ({hints.year})"
        return root

    base = _select_title_by_query(hints, candidate)
    root = base
    if candidate.year is not None:
        root += f" ({candidate.year})"
    if append_tmdb_id and candidate.source == "themoviedb":
        root += f" [tmdbid-{candidate.media_id}]"
    return root


def format_selected_candidate_name(
    candidate: MetadataCandidate, append_tmdb_id: bool = False
) -> str:
    """Format a manually selected result from the exact displayed provider title."""
    root = candidate.title or candidate.en_title or candidate.original_title
    if candidate.year is not None:
        root += f" ({candidate.year})"
    if append_tmdb_id and candidate.source == "themoviedb":
        root += f" [tmdbid-{candidate.media_id}]"
    return root


def format_file_prefix(candidate_title: str) -> str:
    base = _normalize_whitespace(candidate_title)
    base = re.sub(r"\s*\(\d{4}\)$", "", base).strip()
    base = re.sub(r"\s*\[tmdbid-[0-9]+\]\s*$", "", base, flags=re.IGNORECASE).strip()
    return base
