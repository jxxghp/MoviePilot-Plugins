def _ordered_reasons(items: Sequence[str]) -> Tuple[str, ...]:
    unique = list(dict.fromkeys(items))
    return tuple(
        sorted(
            unique,
            key=lambda value: (_REASON_ORDER.get(value, 999), value),
        )
    )

