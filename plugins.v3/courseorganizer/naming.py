def _to_int(value: str) -> Optional[int]:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _parse_year(raw: str) -> Optional[int]:
    match = re.search(r"(?:\(|（)(\d{4})(?:\)|）)", raw)
    if not match:
        return None
    return _to_int(match.group(1))


def _strip_year(raw: str) -> str:
    return re.sub(r"(?:\(|（)\d{4}(?:\)|）)", "", raw).strip()


_CHINESE_NUM_MAP = {
    "零": 0,
    "一": 1,
    "二": 2,
    "三": 3,
    "四": 4,
    "五": 5,
    "六": 6,
    "七": 7,
    "八": 8,
    "九": 9,
    "十": 10,
}


def _parse_chinese_number(raw: str) -> Optional[int]:
    if not raw:
        return None
    if raw.isdigit():
        return _to_int(raw)
    if "十" in raw:
        if raw == "十":
            return 10
        prefix, suffix = raw.split("十", 1)
        if prefix and prefix not in _CHINESE_NUM_MAP:
            return None
        tens = 1 if prefix == "" else _CHINESE_NUM_MAP.get(prefix, 0)
        ones = _CHINESE_NUM_MAP.get(suffix, 0) if suffix else 0
        return tens * 10 + ones
    total = 0
    for char in raw:
        value = _CHINESE_NUM_MAP.get(char)
        if value is None:
            return None
        total += value
    return total or None


_SEASON_NUMBER = r"[0-9零一二三四五六七八九十]+"
_SEASON_RANGE_SEPARATOR = r"(?:[-~～－—–/／]|到|至)"


def _add_season_range(seasons: set, start: Optional[int], end: Optional[int]) -> None:
    """Add a plausible season range without expanding arbitrary large numbers."""
    if start is None or end is None or start < 1 or end < start:
        return
    # Course collections normally use a small, contiguous range.  A bound
    # avoids accidentally treating a video frame range as hundreds of seasons.
    if end > 99 or end - start > 49:
        return
    seasons.update(range(start, end + 1))


def _extract_seasons(value: str) -> Tuple[int, ...]:
    seasons = set()
    # Accept both “第1-8季” and common bare collection forms such as
    # “1-8季” / “1～8季” / “1到8季”.  The trailing 季 keeps ordinary
    # numeric text from being interpreted as a season range.
    for match in re.finditer(
        rf"(?:第\s*)?({_SEASON_NUMBER})\s*{_SEASON_RANGE_SEPARATOR}\s*(?:第\s*)?({_SEASON_NUMBER})\s*季",
        value,
    ):
        _add_season_range(
            seasons,
            _parse_chinese_number(match.group(1)),
            _parse_chinese_number(match.group(2)),
        )
    for match in re.finditer(
        rf"(?i)\bS?\s*0*([0-9]{{1,3}})\s*{_SEASON_RANGE_SEPARATOR}\s*S?\s*0*([0-9]{{1,3}})\b",
        value,
    ):
        _add_season_range(seasons, _to_int(match.group(1)), _to_int(match.group(2)))
    for match in re.finditer(r"第\s*([0-9零一二三四五六七八九十]+)\s*季", value):
        season = _parse_chinese_number(match.group(1))
        if season is not None:
            seasons.add(season)
    for match in re.finditer(r"(?i)\bS\s*0*([0-9]{1,3})\b", value):
        value_int = _to_int(match.group(1))
        if value_int:
            seasons.add(value_int)
    for match in re.finditer(r"(?i)\bSeason\s*0*([0-9]{1,3})\b", value):
        value_int = _to_int(match.group(1))
        if value_int:
            seasons.add(value_int)
    return tuple(sorted(seasons))


def _strip_season_markers(value: str) -> str:
    text = re.sub(
        rf"(?i)\bS\s*0*([0-9]{{1,3}})\s*{_SEASON_RANGE_SEPARATOR}\s*S?\s*0*([0-9]{{1,3}})\b",
        "",
        value,
    )
    text = re.sub(r"(?i)\bS\s*0*([0-9]{1,3})\b", "", text)
    text = re.sub(
        rf"(?i)\bseason\s*0*([0-9]{{1,3}})\s*{_SEASON_RANGE_SEPARATOR}\s*[0-9]{{1,3}}\b",
        "",
        text,
    )
    text = re.sub(r"(?i)\bseason\s*0*([0-9]{1,3})\b", "", text)
    text = re.sub(
        rf"(?:第\s*)?{_SEASON_NUMBER}\s*{_SEASON_RANGE_SEPARATOR}\s*(?:第\s*)?{_SEASON_NUMBER}\s*季",
        "",
        text,
    )
    text = re.sub(r"第\s*[0-9零一二三四五六七八九十]+\s*[季集]\s*", "", text)
    return re.sub(r"\s{2,}", " ", text).strip()


def _strip_empty_brackets(value: str) -> str:
    cleaned = value
    while True:
        updated = re.sub(r"\s*(?:\(\s*\)|（\s*）|\[\s*\]|【\s*】)\s*", " ", cleaned)
        if updated == cleaned:
            break
        cleaned = updated
    return _normalize_whitespace(cleaned)


def _strip_technical_trailing_noise(value: str) -> str:
    """Remove only obvious trailing video/resolution markers from a folder name."""
    cleaned = _normalize_whitespace(value)
    patterns = (
        r"(?i)(?:[\s._\-—–]*)?(?:视频|video)\s*(?:4320|2160|1440|1080|720|576|480)p(?:\s*(?:hd|uhd|hdr|web[- ]?dl|webrip|bluray|x26[45]|h\.?26[45]))*$",
        r"(?i)(?:[\s._\-—–]*)?(?:4320|2160|1440|1080|720|576|480)p(?:\s*(?:hd|uhd|hdr|web[- ]?dl|webrip|bluray|x26[45]|h\.?26[45]))*$",
        r"(?i)(?:[\s._\-—–]*)(?:web[- ]?dl|webrip|bluray|bdrip|hdtv)(?:\s*(?:x26[45]|h\.?26[45]|aac|hevc))?$",
    )
    for pattern in patterns:
        cleaned = re.sub(pattern, "", cleaned).strip()
    return _normalize_whitespace(cleaned)


def _strip_trailing_language_marker(value: str) -> str:
    cleaned = _normalize_whitespace(value)
    marker = (
        r"(?:中英双语(?:版)?|双语(?:版)?|中文(?:配音)?版|国语(?:配音)?版|"
        r"粤语(?:配音)?版|英语(?:配音)?版|日语(?:配音)?版|原声版|中字版)"
    )
    return _normalize_whitespace(re.sub(rf"(?:[\s._\-—–]*){marker}$", "", cleaned, flags=re.IGNORECASE))


def _strip_trailing_noise(value: str) -> str:
    cleaned = _normalize_whitespace(value)
    noise = ("高清修复版", "未删减", "全集", "合集", "抢先版", "主题")
    for marker in noise:
        cleaned = re.sub(
            rf"(?:(?<=^)|(?<=[\s,，。；;:：!！?？()\[\]【】《》])){re.escape(marker)}(?:(?=$)|(?=[\s,，。；;:：!！?？])|(?=[)\]】]))",
            "",
            cleaned,
        )
    cleaned = re.sub(r"\s{2,}", " ", cleaned).strip()
    return cleaned


def _strip_noise_tokens(value: str) -> str:
    cleaned = _normalize_whitespace(value)
    noise = ("高清修复版", "未删减", "全集", "合集", "抢先版", "未删")
    boundary = r"(?:(?<=^)|(?<=[\s,，。；;:：!！?？()\[\]【】《》]))"
    boundary_end = r"(?:(?=$)|(?=[\s,，。；;:：!！?？()\[\]【】]))"
    for marker in noise:
        cleaned = re.sub(
            rf"{boundary}{re.escape(marker)}{boundary_end}",
            "",
            cleaned,
        )
    return _normalize_whitespace(cleaned)


def _book_title(value: str) -> Optional[str]:
    match = re.search(r"《([^》]+)》", value)
    if not match:
        return None
    return _normalize_whitespace(match.group(1))


def _first_clause(value: str) -> str:
    for chunk in re.split(r"[，,：:；;|]", value):
        stripped = chunk.strip()
        if stripped:
            return stripped
    return value.strip()


def _latin_segments(value: str) -> Tuple[str, ...]:
    return tuple(s.strip() for s in re.findall(r"[A-Za-z][A-Za-z0-9 .&'+_-]*[A-Za-z0-9]", value) if s.strip())


def _cjk_segments(value: str) -> Tuple[str, ...]:
    segments: List[str] = []
    for match in re.finditer(r"[\u4e00-\u9fff]{2,}", value):
        segment = match.group(0).strip()
        if not segment:
            continue
        if segment[0].isdigit():
            continue
        if len(segment) > 8:
            continue
        if segment not in segments:
            segments.append(segment)
    return tuple(segments)


def _append_candidate(
    items: List[QueryCandidate], text: str, origin: str, bonus: int = 5
) -> None:
    normalized = normalize_title(text)
    if not normalized:
        return
    for existing in items:
        if normalize_title(existing.text) == normalized:
            return
    items.append(QueryCandidate(text=_normalize_whitespace(text), origin=origin, quality_bonus=bonus))


def parse_title(raw_title: str, manual_query: Optional[str] = None) -> TitleHints:
    raw = _normalize_whitespace(raw_title)
    reason_codes: List[str] = []
    year = _parse_year(raw)
    if year is None:
        reason_codes.append("no_year")
    else:
        reason_codes.append("year")

    body = _strip_year(raw)
    seasons = _extract_seasons(body)
    body = _strip_season_markers(body)
    body = _strip_technical_trailing_noise(body)
    body = _strip_empty_brackets(body)
    body = _strip_trailing_language_marker(body)
    body = _strip_empty_brackets(body)
    body = _strip_noise_tokens(body)
    body = _strip_trailing_noise(body)

    primary = _book_title(body)
    local = _strip_trailing_noise(primary or _first_clause(body))
    local = _strip_trailing_noise(_strip_season_markers(local))
    local = _strip_technical_trailing_noise(local)
    local = _strip_empty_brackets(local)
    local = _strip_trailing_language_marker(local)
    local = _strip_empty_brackets(local)
    if not local:
        reason_codes.append("empty_local")
        local = "Course"

    query_candidates: List[QueryCandidate] = []
    if manual_query:
        _append_candidate(query_candidates, _strip_trailing_noise(_strip_season_markers(manual_query)), "manual")

    if primary:
        _append_candidate(query_candidates, primary, "book_title")

    _append_candidate(query_candidates, local, "first_clause")

    source_text = primary or local
    for item in _latin_segments(source_text):
        _append_candidate(query_candidates, item, "latin_segment")
    for item in _cjk_segments(source_text):
        _append_candidate(query_candidates, item, "cjk_segment")

    return TitleHints(
        raw_title=raw,
        local_title=local,
        year=year,
        season_hints=seasons,
        query_candidates=tuple(query_candidates[:3]),
        reason_codes=tuple(reason_codes),
    )


def parse_manual_overrides(
    raw_text: str, target_libraries: Optional[Iterable[str]] = None
) -> ManualOverrideResult:
    if not isinstance(raw_text, str):
        return ManualOverrideResult(
            (),
            ("invalid_manual_overrides_text",),
            (("", "invalid_manual_overrides_text"),),
        )

    overrides: List[ManualOverride] = []
    seen: Dict[str, ManualOverride] = {}
    errors: List[str] = []
    line_errors: List[Tuple[str, str]] = []
    allowed_targets = (
        {
            str(target).strip().lower()
            for target in target_libraries
            if str(target).strip()
        }
        if target_libraries is not None
        else set(MANUAL_TARGET_LIBRARIES)
    )

    for line in raw_text.splitlines():
        text = line.strip()
        if not text:
            continue
        match = re.match(r"(?P<left>.*?)\s*=>\s*(?P<action>[a-zA-Z_]+)(?:\s*:\s*(?P<value>.*))?\s*$", text)
        if not match:
            errors.append(f"invalid_rule:{text}")
            line_errors.append(("", f"invalid_rule:{text}"))
            continue
        left = _normalize_whitespace(match.group("left"))
        action = match.group("action").strip().lower()
        value = (match.group("value") or "").strip()
        if not left:
            errors.append(f"empty_left:{text}")
            line_errors.append(("", f"empty_left:{text}"))
            continue
        if "=>" in left or "\x00" in left or "\r" in left or "\n" in left:
            errors.append(f"invalid_rule:{text}")
            line_errors.append((left, f"invalid_rule:{text}"))
            continue
        if action not in {"local", "query", "candidate", "ignore", "confirm"}:
            errors.append(f"invalid_rule:{text}")
            line_errors.append((left, f"invalid_rule:{text}"))
            continue

        if action == "ignore":
            if value:
                errors.append(f"invalid_ignore_rule:{text}")
                line_errors.append((left, f"invalid_ignore_rule:{text}"))
                continue
            if left in seen:
                errors.append(f"duplicate_left:{left}")
                line_errors.append((left, f"duplicate_left:{left}"))
                continue
            seen[left] = ManualOverride(left, "ignore")
            continue

        if action == "confirm":
            target, separator, final_name = value.partition(":")
            target_clean = target.strip().lower()
            if (
                not separator
                or target != target.strip()
                or target_clean != target
                or final_name != final_name.strip()
            ):
                error = f"invalid_confirm:{text}"
                errors.append(error)
                line_errors.append((left, error))
                continue
            valid_name, name_error = validate_manual_name(final_name)
            if target_clean not in allowed_targets or not valid_name:
                error = f"invalid_confirm:{text}"
                errors.append(error)
                line_errors.append((left, error if valid_name else name_error))
                continue
            if left in seen:
                errors.append(f"duplicate_left:{left}")
                line_errors.append((left, f"duplicate_left:{left}"))
                continue
            seen[left] = ManualOverride(left, "confirm", final_name, target_clean)
            continue

        if not value:
            errors.append(f"invalid_{action}:{text}")
            line_errors.append((left, f"invalid_{action}:{text}"))
            continue

        if action == "candidate":
            parts = tuple(_normalize_whitespace(part) for part in value.split(":"))
            if len(parts) != 3:
                errors.append(f"invalid_candidate:{text}")
                line_errors.append((left, f"invalid_candidate:{text}"))
                continue
            source, media_id, media_type = parts
            if source not in {"themoviedb", "douban"}:
                errors.append(f"invalid_candidate_source:{text}")
                line_errors.append((left, f"invalid_candidate_source:{text}"))
                continue
            if not media_id:
                errors.append(f"invalid_candidate_id:{text}")
                line_errors.append((left, f"invalid_candidate_id:{text}"))
                continue
            if media_type not in {"movie", "tv", "unknown"}:
                errors.append(f"invalid_candidate_type:{text}")
                line_errors.append((left, f"invalid_candidate_type:{text}"))
                continue
            value = f"{source}:{media_id}:{media_type}"

        if left in seen:
            errors.append(f"duplicate_left:{left}")
            line_errors.append((left, f"duplicate_left:{left}"))
            continue
        seen[left] = ManualOverride(raw_title=left, action=action, value=value)

    overrides.extend(seen.values())
    return ManualOverrideResult(
        overrides=tuple(overrides),
        errors=tuple(errors),
        line_errors=tuple((left, code) for left, code in line_errors),
    )


def query_hash(raw_title: str, queries: Sequence[QueryCandidate], sources: Sequence[str], provider_schema: str = "1") -> str:
    material = {
        "raw_title": raw_title,
        "queries": [q.text for q in queries],
        "query_origins": [q.origin for q in queries],
        "sources": list(sources),
        "parser_schema": PARSER_SCHEMA_VERSION,
        "provider_schema": provider_schema,
    }
    payload = json.dumps(material, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


